"""Analytical SQL runner: executes BI queries on the Star Schema DW and exports dashboard data."""

from __future__ import annotations

from contextlib import closing
import json
import logging
import re
import sqlite3
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from src.config import (
    ANALYTICS_SQL_PATH,
    DASHBOARD_JS_PATH,
    DASHBOARD_JSON_PATH,
    DB_PATH,
    QUALITY_REPORT_PATH,
)

logger = logging.getLogger(__name__)


def parse_named_queries(sql_text: str) -> dict[str, str]:
    """Parse SQL blocks delimited by `-- @name: <identifier>` comments."""
    pattern = re.compile(r"--\s*@name:\s*([a-zA-Z0-9_]+)\s*\n")
    matches = list(pattern.finditer(sql_text))
    queries: dict[str, str] = {}

    for idx, match in enumerate(matches):
        name = match.group(1).strip()
        start = match.end()
        end = matches[idx + 1].start() if idx + 1 < len(matches) else len(sql_text)
        stmt = sql_text[start:end].strip()
        if stmt:
            queries[name] = stmt

    return queries


def execute_analytics(
    db_path: Path = DB_PATH,
    sql_path: Path = ANALYTICS_SQL_PATH,
    quality_report_path: Path = QUALITY_REPORT_PATH,
    output_json_path: Path = DASHBOARD_JSON_PATH,
    output_js_path: Path = DASHBOARD_JS_PATH,
) -> dict[str, Any]:
    """Run all analytical SQL queries and export `dashboard/data.json` + `dashboard/dashboard_data.js`."""
    if not db_path.exists():
        raise FileNotFoundError(f"Data Warehouse SQLite não encontrado: {db_path}")

    sql_text = sql_path.read_text(encoding="utf-8")
    named_queries = parse_named_queries(sql_text)

    results: dict[str, Any] = {}
    with closing(sqlite3.connect(db_path)) as conn:
        conn.row_factory = sqlite3.Row
        for name, query in named_queries.items():
            rows = [dict(r) for r in conn.execute(query).fetchall()]
            results[name] = rows[0] if name == "kpi_overview" and rows else rows
            logger.info("Executed SQL query %-24s | rows=%d", name, len(rows))

    quality_report: dict[str, Any] = {}
    if quality_report_path.exists():
        quality_report = json.loads(quality_report_path.read_text(encoding="utf-8"))

    # Compute ABC class summary for quick cards
    abc_summary: dict[str, dict[str, Any]] = {}
    for cls in ("A", "B", "C"):
        items = [r for r in results.get("abc_curve_products", []) if r.get("classe_abc") == cls]
        abc_summary[cls] = {
            "produtos": len(items),
            "receita": round(sum(i["receita"] for i in items), 2),
            "participacao_pct": round(sum(i["participacao_pct"] for i in items), 2),
        }

    payload: dict[str, Any] = {
        "metadata": {
            "project": "RetailPulse — Pipeline ETL & BI Analítico",
            "generated_at_utc": datetime.now(timezone.utc).isoformat(),
            "warehouse": str(db_path.name),
        },
        "kpi_overview": results.get("kpi_overview", {}),
        "monthly_revenue_growth": results.get("monthly_revenue_growth", []),
        "category_performance": results.get("category_performance", []),
        "regional_performance": results.get("regional_performance", []),
        "abc_curve_products": results.get("abc_curve_products", []),
        "abc_summary": abc_summary,
        "rfm_segmentation": results.get("rfm_segmentation", []),
        "top_customers": results.get("top_customers", []),
        "channel_performance": results.get("channel_performance", []),
        "data_quality_report": quality_report,
    }

    output_json_path.parent.mkdir(parents=True, exist_ok=True)
    json_str = json.dumps(payload, indent=2, ensure_ascii=False)
    output_json_path.write_text(json_str, encoding="utf-8")

    # Embed JSON into JS file so dashboard/index.html works seamlessly over file://
    output_js_path.write_text(
        f"// Auto-generated by src/run_analytics.py — do not edit manually\n"
        f"window.RETAILPULSE_DATA = {json_str};\n",
        encoding="utf-8",
    )

    logger.info("Exported analytics to %s and %s", output_json_path, output_js_path)
    return payload


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
    execute_analytics()
